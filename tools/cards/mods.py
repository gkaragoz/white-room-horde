MODS_EXTRA = {}
try:
    from mods_names import MODS_EXTRA  # type: ignore  # noqa: F401
except ImportError:
    pass


def ts():
    out = [
        "// Generated by tools/cards/mods.py: do not edit by hand.",
        "export interface ModDef {",
        "  id: string;",
        "  /** Adds weight / 20 to the score multiplier. */",
        "  weight: number;",
        "  fx: Readonly<Record<string, number>>;",
        "  text: Record<'en' | 'tr' | 'de' | 'es' | 'fr' | 'ru', readonly [string, string]>;",
        "}",
        "",
        "export const MODS = [",
    ]
    for i, (mid, weight, fx, en, tr) in enumerate(M):
        extra = MODS_EXTRA.get(mid, {})
        texts = {"en": en, "tr": tr}
        for lang in ("de", "es", "fr", "ru"):
            texts[lang] = tuple(extra.get(lang, en))
        t = ", ".join("%s: [%s, %s]" % (k, q(v[0]), q(v[1])) for k, v in texts.items())
        f = ", ".join("%s: %s" % (k, v) for k, v in fx.items())
        out.append("  { id: '%s', weight: %d, fx: { %s }, text: { %s } }," % (mid, weight, f, t))
    out.append("] as const satisfies readonly ModDef[];")
    out.append("")
    out.append("export const MOD_COUNT = MODS.length;")
    out.append("/** The score multiplier of a set of mods (bit n = MODS[n]). 1 with none, about 3.6 with all of them. */")
    out.append("export function scoreMultiplier(mods: number): number {")
    out.append("  let sum = 0;")
    out.append("  for (let i = 0; i < MODS.length; i++) if ((mods >> i) & 1) sum += MODS[i]!.weight;")
    out.append("  return 1 + sum / 20;")
    out.append("}")
    out.append("")
    return "\n".join(out)


