// Reads the Discovery Track table (docs/wayfinder/meta-progression/discovery-track.md) and writes
// packages/shared/src/track.ts: the unlock schedule, the enemy pressure table and the XP thresholds.
// Nothing in track.ts is edited by hand; change the table or the constants below and run
//
//   node tools/cards/track.mjs
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const doc = fs.readFileSync(root + 'docs/wayfinder/meta-progression/discovery-track.md', 'utf8').replace(/\r\n/g, '\n');

const MAX_LEVEL = 100;
/** XP of one reference run (a typical run's worth); the level steps are fractions of it. */
const R = 1000;
/** Enemy pressure p(L) = 0.45 + 0.55 ((L-1)/59)^1.6 up to this level, 1.0 after. */
const PRESSURE_FULL_LEVEL = 60;

const CATEGORY = {
  class: 'class',
  silah: 'weapon',
  drone: 'drone',
  arena: 'arena',
  'kart paketi': 'pack',
  'güç-artırıcı': 'powerup',
  elit: 'elite',
  'zorluk çarpanı': 'mod',
};

const items = [];
const levelsSeen = new Set();
for (const line of doc.split('\n')) {
  const m = line.match(/^\| (\d+) \| (.*) \| (.*) \|$/);
  if (!m) continue;
  const level = Number(m[1]);
  if (levelsSeen.has(level)) throw new Error(`level ${level} listed twice`);
  levelsSeen.add(level);
  if (m[2] !== '-') {
    for (const raw of m[2].split(', ')) {
      const [catName, rest] = raw.split(': ');
      const cat = CATEGORY[catName];
      if (!cat || !rest) throw new Error(`level ${level}: cannot read "${raw}"`);
      const withPack = rest.endsWith(' (+ temel kart paketi)');
      const core = rest.endsWith(' (Core)');
      const name = rest.replace(' (+ temel kart paketi)', '').replace(' (Core)', '');
      if (cat === 'pack') {
        const cp = name.match(/^(\w+) (temel|ileri)$/);
        items.push({ level, cat, name: cp ? `${cp[1]}:${cp[2] === 'temel' ? 'basic' : 'adv'}` : name });
      } else {
        items.push({ level, cat, name, core });
        if (withPack) items.push({ level, cat: 'pack', name: `${name}:basic`, bundled: true });
      }
    }
  }
  if (m[3] !== '-') items.push({ level, cat: 'cosmetic', name: m[3] });
}
for (let l = 1; l <= MAX_LEVEL; l++) if (!levelsSeen.has(l)) throw new Error(`level ${l} is missing from the table`);

const pressure = [0];
for (let l = 1; l <= MAX_LEVEL; l++) {
  const p = l >= PRESSURE_FULL_LEVEL ? 1 : 0.45 + 0.55 * Math.pow((l - 1) / (PRESSURE_FULL_LEVEL - 1), 1.6);
  pressure.push(Math.round(p * 1000));
}

/** XP to climb from level l to l+1, as a fraction of R: three bands, each rising linearly. */
function stepFactor(l) {
  if (l <= 10) return 0.45 + (0.75 - 0.45) * ((l - 1) / 9);
  if (l <= 50) return 0.75 + (1.125 - 0.75) * ((l - 11) / 39);
  return 1.125 + (1.875 - 1.125) * ((l - 51) / 49);
}
const xp = [0, 0];
for (let l = 1; l < MAX_LEVEL; l++) xp.push(xp[l] + Math.round(R * stepFactor(l)));

const rows = items
  .map((i) => `  { level: ${i.level}, cat: '${i.cat}', name: '${i.name}'${i.core ? ', core: true' : ''}${i.bundled ? ', bundled: true' : ''} },`)
  .join('\n');
const out = `// Generated by tools/cards/track.mjs from docs/wayfinder/meta-progression/discovery-track.md. Do not edit by hand.

export const MAX_LEVEL = ${MAX_LEVEL};
/** XP of one reference run: the level steps below are fractions of it. */
export const XP_REFERENCE_RUN = ${R};

export type TrackCategory = 'class' | 'weapon' | 'drone' | 'arena' | 'pack' | 'powerup' | 'elite' | 'mod' | 'cosmetic';
export interface TrackItem {
  readonly level: number;
  readonly cat: TrackCategory;
  readonly name: string;
  /** Part of the starting set: available from level 1 and never locked. */
  readonly core?: true;
  /** A class's basic card pack: opens with the class and counts as part of that one reward. */
  readonly bundled?: true;
}

/** What each level opens, in table order. */
export const TRACK: readonly TrackItem[] = [
${rows}
];

/**
 * Enemy pressure by meta level (index 1..${MAX_LEVEL}) in thousandths: p = 0.45 + 0.55 ((L-1)/59)^1.6 up to level ${PRESSURE_FULL_LEVEL}, 1000 after.
 * An integer table so the simulation never has to evaluate a power.
 */
export const PRESSURE_PERMILLE: readonly number[] = [${pressure.join(', ')}];

/** Total XP needed to reach each level (index 1..${MAX_LEVEL}); level 1 needs none. */
export const XP_FOR_LEVEL: readonly number[] = [${xp.join(', ')}];
`;
fs.writeFileSync(root + 'packages/shared/src/track.ts', out);
console.log(`track.ts: ${items.length} items, level ${MAX_LEVEL} needs ${xp[MAX_LEVEL]} XP (${(xp[MAX_LEVEL] / R).toFixed(1)} R)`);
