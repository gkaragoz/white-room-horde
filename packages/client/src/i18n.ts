/** Cards are written as [title, text] in the card pool order, then turned into the object the UI reads. */
function cards(list: [string, string][]): Record<string, [string, string]> {
  return Object.fromEntries(CARD_KEYS.map((k, i) => [k, list[i]!]));
}

